"""Run every baseline across seeds, evaluate on validation and test, log to MLflow, write the report."""

import json
import time
from pathlib import Path
from typing import Any

import mlflow
import pandas as pd
import torch

from basketmind.baselines.models import (
    GRURecommender,
    ItemItemCF,
    MatrixFactorisation,
    Popularity,
    Recommender,
)
from basketmind.baselines.task import Task, load_task
from basketmind.evaluation.ranking import RankingMetrics
from basketmind.utils.config import load_config, project_root
from basketmind.utils.device import describe_device, get_device
from basketmind.utils.logging import get_logger

log = get_logger("baselines")
REPORT_COLS = ["recall@5", "recall@10", "recall@20", "precision@10", "ndcg@10", "mrr"]


@torch.no_grad()
def evaluate_model(
    model: Recommender,
    task: Task,
    split: str,
    policy: str,
    ks: list[int],
    device: torch.device,
    batch_size: int = 512,
) -> dict[str, float]:
    """Rank the whole catalogue for every example of `split` and return the metrics."""
    ex = task.examples[split]
    meter = RankingMetrics(ks)
    for s in range(0, len(ex), batch_size):
        batch = ex.iloc[s : s + batch_size]
        exclude = task.history_hot(batch, device) > 0 if policy == "exclude_history" else None
        meter.update(model.score(task, batch, device), task.target_hot(batch, device), exclude)
    return meter.compute()


def _models(cfg: dict[str, Any], train_cfg: dict[str, Any]) -> list[Recommender]:
    return [
        Popularity(),
        ItemItemCF(),
        MatrixFactorisation(cfg["matrix_factorisation"]),
        GRURecommender(cfg["gru"], train_cfg),
    ]


def aggregate(results: pd.DataFrame) -> pd.DataFrame:
    """Mean and std over seeds per (model, split, policy)."""
    metrics = [c for c in results.columns if c not in {"model", "seed", "split", "policy"}]
    g = results.groupby(["model", "split", "policy"], sort=False)[metrics]
    mean, std = g.mean(), g.std(ddof=0)
    return mean.join(std.add_suffix("_std")).reset_index()


def render_report(agg: pd.DataFrame, task: Task, cfg: dict[str, Any], seeds: list[int], meta: dict) -> str:
    def table(split: str, policy: str) -> str:
        rows = ["| model | " + " | ".join(REPORT_COLS) + " | n |", "|---|" + "---:|" * (len(REPORT_COLS) + 1)]
        sub = agg[(agg["split"] == split) & (agg["policy"] == policy)]
        for _, r in sub.iterrows():
            cells = [f"{r[c]:.4f} ± {r[c + '_std']:.4f}" for c in REPORT_COLS]
            rows.append(f"| {r['model']} | " + " | ".join(cells) + f" | {int(r['n_evaluated']):,} |")
        return "\n".join(rows)

    st = task.stats["splits"]
    cov = {
        s: f"{v['target_items_in_catalogue'] / v['target_items_total']:.1%} of target items in catalogue"
        for s, v in st.items()
    }
    return f"""# Baseline comparison

Generated by `scripts/run_baselines.py`. Real results on the Online Retail II data; do not edit by hand.
Mean ± standard deviation over seeds {seeds} (popularity and item-item CF are deterministic, so std is 0).
Hyperparameters are fixed in `configs/baselines.yaml`. The GRU (30 trials) and matrix factorisation
(40 trials) were each tuned with Optuna on validation `{cfg["selection_metric"]}` only (`docs/gru_tuning.md`,
`docs/matrix_factorisation_tuning.md`). Popularity and item-item CF have no hyperparameters.
Early stopping and epoch choice use validation only; test numbers are reported, never used for selection.

## Setup
- Catalogue: {task.n_items:,} products seen in the training baskets. Target items outside it are dropped
  ({cov["validation"]} in validation, {cov["test"]} in test); examples left with no target are skipped.
- Ranking is over the whole catalogue. Policy `full` allows repeat purchases; `exclude_history` removes the
  customer's history items from the candidates and from the targets (new-item discovery only).
- Device: {meta["device"]}.

## Test, policy `full`
{table("test", "full")}

## Test, policy `exclude_history`
{table("test", "exclude_history")}

## Validation, policy `full`
{table("validation", "full")}

## Validation, policy `exclude_history`
{table("validation", "exclude_history")}

## Notes
- Matrix factorisation is fit on training baskets only; customers with no training basket use a
  popularity-like item bias. Its customer vectors are not updated with later baskets, so it is weaker for
  late-period customers.
- Popularity is static (training counts); no model sees validation or test baskets during fitting.
"""


def run_baselines(root: Path | None = None) -> pd.DataFrame:
    root = root or project_root()
    cfg = load_config("baselines", root / "configs")
    train_cfg = load_config("training", root / "configs")
    ks = load_config("evaluation", root / "configs")["recommendation_k"]
    seeds = train_cfg["seeds"]
    device = get_device(train_cfg["device"])
    out = root / cfg["output_dir"]
    out.mkdir(parents=True, exist_ok=True)

    task = load_task(root / load_config("data", root / "configs")["processed_dir"])
    log.info("catalogue %d items; examples %s", task.n_items, {s: len(e) for s, e in task.examples.items()})

    mlflow.set_tracking_uri(f"sqlite:///{(root / 'experiments' / 'mlflow.db').as_posix()}")
    mlflow.set_experiment(cfg["mlflow"]["experiment"])
    sel_key = cfg["selection_metric"]

    rows: list[dict[str, Any]] = []
    details: dict[str, Any] = {}
    for model in _models(cfg, train_cfg):
        for seed in seeds if model.stochastic else seeds[:1]:
            with mlflow.start_run(run_name=f"{model.name}-seed{seed}"):
                mlflow.log_params({"model": model.name, "seed": seed, "device": str(device)})
                mlflow.log_params({f"cfg.{k}": v for k, v in (cfg.get(model.name) or {}).items()})
                t0 = time.time()

                def val_metric(m: Recommender) -> float:
                    return evaluate_model(m, task, "validation", "full", ks, device)[sel_key]

                info = model.fit(task, device, seed, val_metric)
                fit_s = time.time() - t0
                mlflow.log_metric("fit_seconds", fit_s)
                details[f"{model.name}-{seed}"] = {k: v for k, v in info.items() if k != "history"} | {
                    "fit_seconds": round(fit_s, 1),
                    "history": info.get("history", []),
                }
                for split in ("validation", "test"):
                    for policy in cfg["candidate_policies"]:
                        m = evaluate_model(model, task, split, policy, ks, device)
                        rows.append(
                            {"model": model.name, "seed": seed, "split": split, "policy": policy, **m}
                        )
                        mlflow.log_metrics(
                            {f"{split}.{policy}.{k.replace('@', '_at_')}": v for k, v in m.items()}
                        )
                log.info("%s seed %d done in %.0fs", model.name, seed, fit_s)

    results = pd.DataFrame(rows)
    results.to_csv(out / "results.csv", index=False)
    (out / "run_details.json").write_text(json.dumps(details, indent=2, default=str), encoding="utf-8")
    agg = aggregate(results)
    agg.to_csv(out / "summary.csv", index=False)
    meta = {"device": str(describe_device())}
    (root / cfg["report_path"]).write_text(render_report(agg, task, cfg, seeds, meta), encoding="utf-8")
    return agg
