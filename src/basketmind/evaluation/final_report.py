"""Final comparison: BasketMind variants (mean +- std over seeds) next to the baselines."""

import json
from pathlib import Path

import pandas as pd

METRICS = ["recall@5", "recall@10", "recall@20", "precision@10", "ndcg@10", "mrr"]
POLICIES = ("full", "exclude_history")


def load_neural(neural_dir: Path, variants: list[str]) -> pd.DataFrame:
    """One row per (variant, seed, split, policy). Test rows exist only for runs evaluated on test."""
    rows = []
    for variant in variants:
        for run in sorted((neural_dir / variant).glob("seed*")):
            sources = {"validation": run / "result.json", "test": run / "test_result.json"}
            for split, path in sources.items():
                if not path.exists():
                    continue
                d = json.loads(path.read_text())[split]
                for policy in POLICIES:
                    rows.append(
                        {
                            "variant": variant,
                            "seed": int(run.name.removeprefix("seed")),
                            "split": split,
                            "policy": policy,
                            "n": d[f"{policy}.n_evaluated"],
                            **{m: d[f"{policy}.{m}"] for m in METRICS},
                        }
                    )
    return pd.DataFrame(rows)


def aggregate(runs: pd.DataFrame) -> pd.DataFrame:
    g = runs.groupby(["variant", "split", "policy"], sort=False)
    mean, std = g[METRICS].mean(), g[METRICS].std(ddof=0)
    return (
        mean.join(std.add_suffix("_std"))
        .join(g.agg(seeds=("seed", "nunique"), n=("n", "first")))
        .reset_index()
    )


def select_variant(agg: pd.DataFrame, candidates: list[str], metric: str = "recall@10") -> str:
    """The candidate with the best mean VALIDATION metric (policy `full`). Test is never consulted."""
    val = agg[(agg["split"] == "validation") & (agg["policy"] == "full") & agg["variant"].isin(candidates)]
    return str(val.sort_values(metric, ascending=False).iloc[0]["variant"])


def baseline_rows(summary_csv: Path) -> pd.DataFrame:
    s = pd.read_csv(summary_csv).rename(columns={"model": "variant", "n_evaluated": "n"})
    s["seeds"] = s["variant"].map(lambda v: 1 if v in ("popularity", "item_item_cf") else 3)
    return s[["variant", "split", "policy", "n", "seeds", *METRICS, *[m + "_std" for m in METRICS]]]


PERSONAL = "personal_frequency"  # added after the course report; see docs/repeat_purchases.md


def personal_frequency_rows(path: Path, baselines: pd.DataFrame) -> pd.DataFrame:
    """Rows for the personal-frequency baseline from scripts/run_repeat_baselines.py (one seed).

    Test uses the same examples as every other model, so its example counts are copied from item-item CF.
    """
    d = json.loads(path.read_text())[PERSONAL]
    n_test = baselines[baselines["variant"] == "item_item_cf"].set_index(["split", "policy"])["n"]
    rows = []
    for split, per_policy in (("validation", d["validation"]), ("test", d["test_means"])):
        for policy in POLICIES:
            m = per_policy[policy]
            n = m["n_evaluated"] if split == "validation" else n_test[(split, policy)]
            rows.append(
                {"variant": PERSONAL, "split": split, "policy": policy, "n": n, "seeds": 1}
                | {k: m[k] for k in METRICS}
                | {k + "_std": 0.0 for k in METRICS}
            )
    return pd.DataFrame(rows)


def render(agg: pd.DataFrame, baselines: pd.DataFrame, selected: str) -> str:
    def table(split: str, policy: str) -> str:
        head = "| model | seeds | " + " | ".join(METRICS) + " |"
        lines = [head, "|---|---:|" + "---:|" * len(METRICS)]
        for frame, mark in ((baselines, False), (agg, True)):
            for _, r in frame[(frame["split"] == split) & (frame["policy"] == policy)].iterrows():
                name = r["variant"] + (" **(selected)**" if mark and r["variant"] == selected else "")
                name += " *(added after the course report)*" if r["variant"] == PERSONAL else ""
                cells = " | ".join(f"{r[m]:.4f} ± {r[m + '_std']:.4f}" for m in METRICS)
                lines.append(f"| {name} | {int(r['seeds'])} | {cells} |")
        return "\n".join(lines)

    note = (
        "\n`personal_frequency` ranks a customer's own past products by recency-weighted purchase count. "
        "It was added after the course report, which therefore calls item-item CF the strongest baseline; "
        "this table is the corrected comparison. See [repeat_purchases.md](repeat_purchases.md).\n"
        if PERSONAL in set(baselines["variant"])
        else ""
    )
    return f"""# Final comparison

Generated by `scripts/report_final.py` from real runs; do not edit by hand. Mean ± standard deviation over
seeds (popularity, item-item CF and personal frequency are deterministic). Ranking is over the catalogue.
Policy `full` allows repeat purchases; `exclude_history` scores only items new to the customer.
{note}
**Model selection.** The final BasketMind variant is **{selected}**, chosen as the variant with the best mean
validation Recall@10 over its seeds. The test split played no part in that choice and was evaluated once per
run, from the best-validation checkpoint.

## Test, policy `full`
{table("test", "full")}

## Test, policy `exclude_history`
{table("test", "exclude_history")}

## Validation, policy `full`
{table("validation", "full")}

## Validation, policy `exclude_history`
{table("validation", "exclude_history")}
"""
