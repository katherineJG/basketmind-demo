"""M1 pipeline: raw -> labelled events -> baskets -> splits -> sequences -> examples, plus reports."""

import json
from pathlib import Path
from typing import Any

import pandas as pd

from basketmind.data.baskets import aggregate_baskets, create_temporal_splits
from basketmind.data.clean import clean_transactions
from basketmind.data.ingest import load_raw_data, validate_raw_data
from basketmind.sequences.build import (
    build_customer_sequences,
    build_next_basket_examples,
    verify_temporal_integrity,
)
from basketmind.utils.config import load_config, project_root
from basketmind.utils.logging import get_logger

log = get_logger("data.pipeline")


def build_quality_report(
    validation: dict[str, Any],
    events: pd.DataFrame,
    baskets: pd.DataFrame,
    split_meta: dict[str, Any],
    sequences: pd.DataFrame,
    examples: pd.DataFrame,
    integrity: dict[str, int],
) -> dict[str, Any]:
    """Collect every number the data quality report and the course report will cite."""
    by_event = events.groupby("event_type").agg(rows=("InvoiceNo", "size"), invoices=("InvoiceNo", "nunique"))
    canc = events[events["event_type"] == "cancellation"]
    purch = events[events["event_type"] == "purchase"]
    anon_inv = purch.loc[~purch["has_customer"], "InvoiceNo"].nunique()
    train_customers = set(baskets.loc[baskets["split"] == "train", "CustomerID"])
    per_split_cold = {}
    for s in ("validation", "test"):
        cust = set(baskets.loc[baskets["split"] == s, "CustomerID"])
        per_split_cold[s] = {
            "customers": len(cust),
            "unseen_in_train": len(cust - train_customers),
        }
    stamps = events.groupby("InvoiceNo")["InvoiceDate"].nunique()
    return {
        "raw": validation,
        "event_types": by_event.to_dict("index"),
        "non_product_top_codes": events.loc[events["event_type"] == "non_product", "StockCode"]
        .value_counts()
        .head(10)
        .to_dict(),
        "anonymous_purchase_invoices": int(anon_inv),
        "anonymous_purchase_rows": int((~purch["has_customer"]).sum()),
        "cancellations": {
            "rows": len(canc),
            "invoices": int(canc["InvoiceNo"].nunique()),
            "rows_with_customer": int(canc["has_customer"].sum()),
        },
        "within_sheet_exact_duplicate_lines_kept": int(
            purch.duplicated(["InvoiceNo", "StockCode", "Quantity", "InvoiceDate", "UnitPrice"]).sum()
        ),
        "invoices_spanning_multiple_timestamps": int((stamps > 1).sum()),
        "baskets": {
            "count": len(baskets),
            "customers": int(baskets["CustomerID"].nunique()),
            "distinct_products": int(baskets["items"].explode().nunique()),
            "basket_size": baskets["n_items"].describe().round(2).to_dict(),
            "baskets_per_customer": sequences["n_baskets"].describe().round(2).to_dict(),
            "single_basket_customers": int((sequences["n_baskets"] == 1).sum()),
            "same_customer_same_timestamp_baskets": int(
                baskets.duplicated(["CustomerID", "timestamp"]).sum()
            ),
        },
        "splits": split_meta,
        "cold_start": per_split_cold,
        "examples": {
            "total": len(examples),
            "per_split": examples["split"].value_counts().to_dict(),
            "first_baskets_without_history": len(baskets) - len(examples),
        },
        "temporal_integrity": integrity,
    }


def render_markdown(r: dict[str, Any]) -> str:
    """Human-readable data quality report (written to docs/data_quality_report.md)."""
    ev = "\n".join(f"| {k} | {v['rows']:,} | {v['invoices']:,} |" for k, v in r["event_types"].items())
    sp = "\n".join(
        f"| {k} | {r['splits']['baskets'].get(k, 0):,} | {r['splits']['customers'].get(k, 0):,} | "
        f"{r['splits']['observed'].get(k, ['-', '-'])[0][:10]} to {r['splits']['observed'].get(k, ['-', '-'])[1][:10]} | "
        f"{r['examples']['per_split'].get(k, 0):,} |"
        for k in ("train", "validation", "test", "unassigned")
    )
    b, c = r["baskets"], r["cancellations"]
    return f"""# Data quality report

Generated by `scripts/run_m1.py` from the real UCI Online Retail II file. Do not edit by hand.

## Raw data
- Rows: {r["raw"]["rows"]:,} ({r["raw"]["date_min"][:10]} to {r["raw"]["date_max"][:10]})
- Null CustomerID: {r["raw"]["null_counts"]["CustomerID"]:,} rows (never merged into one customer)
- Null Description: {r["raw"]["null_counts"]["Description"]:,} rows
- Negative-quantity rows: {r["raw"]["negative_quantity_rows"]:,}; non-positive-price rows: {r["raw"]["non_positive_price_rows"]:,}

## Row labels (every row is kept and labelled)
| event_type | rows | invoices |
|---|---:|---:|
{ev}

- Top non-product codes: {r["non_product_top_codes"]}
- Anonymous purchase invoices (no CustomerID, excluded from sequences): {r["anonymous_purchase_invoices"]:,}
- Cancellations: {c["rows"]:,} rows on {c["invoices"]:,} invoices, {c["rows_with_customer"]:,} rows with a customer
- Within-sheet exact duplicate purchase lines (kept, quantities summed): {r["within_sheet_exact_duplicate_lines_kept"]:,}
- Invoices spanning several timestamps (earliest used): {r["invoices_spanning_multiple_timestamps"]:,}

## Baskets
- Baskets: {b["count"]:,} from {b["customers"]:,} customers; {b["distinct_products"]:,} distinct products
- Basket size (distinct products): {b["basket_size"]}
- Baskets per customer: {b["baskets_per_customer"]}
- Customers with a single basket: {b["single_basket_customers"]:,}
- Same-customer baskets sharing a timestamp: {b["same_customer_same_timestamp_baskets"]:,} (excluded from each other's history)

## Chronological splits (provisional boundaries)
| split | baskets | customers | observed range | examples |
|---|---:|---:|---|---:|
{sp}

Cold start (customers with baskets in the split but none in train): {r["cold_start"]}

## Next-basket examples
- Total: {r["examples"]["total"]:,}; first baskets without history (not examples): {r["examples"]["first_baskets_without_history"]:,}

## Temporal integrity
- {r["temporal_integrity"]["examples_checked"]:,} examples checked: no future or tied basket in any history, no cross-customer
  history, target never in its own history. Passed.
"""


def run_m1(refresh: bool = False, root: Path | None = None) -> dict[str, Any]:
    """Run the whole M1 pipeline and write artefacts to data/processed and docs/."""
    root = root or project_root()
    cfg = load_config("data", root / "configs")
    feat = load_config("features", root / "configs")
    cfg = {**cfg, "raw_cache_path": root / cfg["raw_cache_path"]}
    out = root / cfg["processed_dir"]
    out.mkdir(parents=True, exist_ok=True)

    raw = load_raw_data(root / cfg["raw_path"], cfg, refresh=refresh)
    validation = validate_raw_data(raw, cfg)
    events = clean_transactions(raw, cfg)
    baskets, split_meta = create_temporal_splits(aggregate_baskets(events), cfg)
    sequences = build_customer_sequences(baskets)
    examples = build_next_basket_examples(sequences, feat)
    integrity = verify_temporal_integrity(examples, baskets)

    events[events["event_type"] == "purchase"].to_parquet(out / "purchase_events.parquet")
    events[events["event_type"] == "cancellation"].to_parquet(out / "cancellation_events.parquet")
    events[~events["event_type"].isin(["purchase", "cancellation"])].to_parquet(out / "other_events.parquet")
    baskets.to_parquet(out / "baskets.parquet")
    sequences.to_parquet(out / "customer_sequences.parquet")
    examples.to_parquet(out / "next_basket_examples.parquet")

    report = build_quality_report(validation, events, baskets, split_meta, sequences, examples, integrity)
    (out / "split_metadata.json").write_text(json.dumps(split_meta, indent=2, default=str), encoding="utf-8")
    (out / "data_quality_report.json").write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    (root / "docs" / "data_quality_report.md").write_text(render_markdown(report), encoding="utf-8")
    log.info("M1 complete: %d baskets, %d examples", len(baskets), len(examples))
    return report
